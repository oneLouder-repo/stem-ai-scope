#!/usr/bin/env python3
"""Pack every JSON/Markdown data file into data/bundle.js so the site also works
when opened straight from disk (file://), where browsers block fetch().
Pages load the bundle only when opened from disk; on a web server they fetch live files."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
files = sorted(ROOT.glob("data/*.json")) + sorted(ROOT.glob("data/roundups/*.json"))
bundle = {str(f.relative_to(ROOT)).replace("\\", "/"): json.loads(f.read_text(encoding="utf-8")) for f in files}
for f in sorted(ROOT.glob("content/*.md")):
    bundle[str(f.relative_to(ROOT)).replace("\\", "/")] = f.read_text(encoding="utf-8")
out = ROOT / "data" / "bundle.js"
out.write_text("// Generated by scripts/build_bundle.py. Do not edit.\nwindow.SCOPE_DATA = " +
               json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"bundle.js: {len(bundle)} files, {out.stat().st_size // 1024} KB")
